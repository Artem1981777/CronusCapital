import { readFileSync, writeFileSync } from "node:fs"
import solc from "solc"

const source = readFileSync("contracts/CronusProofNote.sol", "utf8")
const input = {
  language: "Solidity",
  sources: { "CronusProofNote.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
}
const output = JSON.parse(solc.compile(JSON.stringify(input)))
const errors = (output.errors || []).filter((e) => e.severity === "error")
if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"))
const c = output.contracts["CronusProofNote.sol"].CronusProofNote
if (!c.evm.bytecode.object) throw new Error("Compiler returned empty bytecode")
const rendered = `// Generated by scripts/compile-proof-note.mjs. Do not edit manually.\nexport const cronusProofNoteAbi = ${JSON.stringify(c.abi, null, 2)} as const\nexport const cronusProofNoteBytecode = "0x${c.evm.bytecode.object}" as const\n`
writeFileSync("src/contracts/cronusProofNoteArtifact.ts", rendered)
console.log(`compiled CronusProofNote: ${c.evm.bytecode.object.length / 2} bytes`)
