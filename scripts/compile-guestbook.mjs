import { readFileSync, writeFileSync } from "node:fs"
import solc from "solc"

const source = readFileSync("contracts/CronusGuestbook.sol", "utf8")
const input = {
  language: "Solidity",
  sources: { "CronusGuestbook.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
}
const output = JSON.parse(solc.compile(JSON.stringify(input)))
const errors = (output.errors || []).filter((e) => e.severity === "error")
if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"))
const c = output.contracts["CronusGuestbook.sol"].CronusGuestbook
if (!c.evm.bytecode.object) throw new Error("Compiler returned empty bytecode")
const rendered = `// Generated by scripts/compile-guestbook.mjs. Do not edit manually.\nexport const cronusGuestbookAbi = ${JSON.stringify(c.abi, null, 2)} as const\nexport const cronusGuestbookBytecode = "0x${c.evm.bytecode.object}" as const\n`
writeFileSync("src/contracts/cronusGuestbookArtifact.ts", rendered)
console.log(`compiled CronusGuestbook: ${c.evm.bytecode.object.length / 2} bytes`)
